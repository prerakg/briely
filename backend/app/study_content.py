"""Typed generated study content and deterministic, safe Mermaid compilation."""

import re
from pydantic import BaseModel, ConfigDict, Field, model_validator
from typing import Literal


class ContentModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class KeyTerm(ContentModel):
    term: str = Field(min_length=1)
    definition: str = Field(min_length=1)


class Summary(ContentModel):
    overview: str = Field(min_length=1)
    mainPoints: list[str] = Field(min_length=1, max_length=12)
    keyTerms: list[KeyTerm] = Field(max_length=16)


class Flashcard(ContentModel):
    front: str = Field(min_length=1)
    back: str = Field(min_length=1)
    difficulty: Literal["Easy", "Medium", "Hard"]
    topic: str = Field(min_length=1)


class Cards(ContentModel):
    items: list[Flashcard] = Field(min_length=1, max_length=16)


class Topic(ContentModel):
    timestamp: float = Field(ge=0)
    topic: str = Field(min_length=1)


class Topics(ContentModel):
    items: list[Topic] = Field(min_length=1, max_length=24)


class Text(ContentModel):
    text: str = Field(min_length=1)


class MapNode(ContentModel):
    id: str = Field(pattern=r"^n[0-9]+$")
    label: str = Field(min_length=1, max_length=160)


class MapEdge(ContentModel):
    source: str
    target: str


class MindMap(ContentModel):
    nodes: list[MapNode] = Field(min_length=2, max_length=24)
    edges: list[MapEdge] = Field(min_length=1, max_length=32)

    @model_validator(mode="after")
    def valid_graph(self):
        ids = {node.id for node in self.nodes}
        if len(ids) != len(self.nodes):
            raise ValueError("Use unique node IDs")
        connected = set()
        for edge in self.edges:
            if (
                edge.source not in ids
                or edge.target not in ids
                or edge.source == edge.target
            ):
                raise ValueError("Edges must connect distinct existing node IDs")
            connected.update((edge.source, edge.target))
        if connected != ids:
            raise ValueError("Connect every concept to the map")
        reached = {self.nodes[0].id}
        while True:
            previous = len(reached)
            for edge in self.edges:
                if edge.source in reached or edge.target in reached:
                    reached.update((edge.source, edge.target))
            if len(reached) == previous:
                break
        if reached != ids:
            raise ValueError("Return one connected concept map")
        return self

    def mermaid(self):
        lines = ["graph TD"]
        for node in self.nodes:
            # Keep labels as plain text; graph syntax is generated by the server.
            label = re.sub(r"[\x00-\x1f\x7f]", " ", node.label)
            label = (
                label.replace("&", "&amp;")
                .replace('"', "&quot;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("`", "'")
            )
            lines.append(f'{node.id}["{label}"]')
        lines.extend(f"{edge.source} --> {edge.target}" for edge in self.edges)
        return "\n".join(lines)


CONTENT_MODELS = {
    "summary": Summary,
    "flashcards": Cards,
    "topics": Topics,
    "mindmap": MindMap,
    "notes": Text,
}


def normalize_content(task, value):
    if not isinstance(value, dict):
        raise ValueError("Return the required JSON object")
    data = dict(value)
    if task == "summary":
        for old, new in [("main_points", "mainPoints"), ("key_terms", "keyTerms")]:
            if old in data and new not in data:
                data[new] = data.pop(old)
    if task == "flashcards" and isinstance(data.get("items"), list):
        data["items"] = [
            dict(item, difficulty=item.get("difficulty", "").title())
            if isinstance(item, dict) and isinstance(item.get("difficulty"), str)
            else item
            for item in data["items"]
        ]
    model = CONTENT_MODELS[task].model_validate(data)
    if task == "mindmap":
        return model.mermaid()
    if task in ("flashcards", "topics"):
        return [item.model_dump() for item in model.items]
    if task == "notes":
        return model.text
    return model.model_dump()
